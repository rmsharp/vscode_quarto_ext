// truth.mjs -- the pandoc-truth fixture generator for the attribute tokenizer (plan P2, DONE items 3 and 4).
//
//   node docs/planning/scripts/attribute-block/truth.mjs --write   regenerate test/unit/attribute-block-truth.json
//   node docs/planning/scripts/attribute-block/truth.mjs --check   regenerate in memory, diff against the
//                                                                  committed fixture, run the built-in controls;
//                                                                  exit 0 only if both agree.
//
// WHAT IT DOES. Every synthetic spec below is written as a `:::` opener in two framings, under each of two
// pandoc dialects, and read back through live `quarto pandoc` (3.6.3): ONE `-t json` call per dialect.
//   oneLine:      `::: <spec>` / blank / `x` / blank / `:::`
//   continuation: `::: <spec>` / `}`  / blank / `x` / blank / `:::`   (does a "refused" verdict stay final?)
// Rows of a dialect are separated by sentinel paragraphs. A spec holding a TAB is written at indents 0 and 1
// (pandoc expands TABs to 4-column stops of the PHYSICAL line; what `\<TAB>` becomes depends on the column it sits at:
// `{k=a\<TAB>b}` -> 3 spaces, `{kkk=a\<TAB>b}` -> 1 space, both at indent 0 -- pandoc-markdown B26). MEASURED: pandoc 3.6.3
// does not open a div from an INDENTED `:::` at all (1-3 spaces, plain spaces too), so every indent>0 row is "refused".
//
// CLASSIFICATION (deliberately RAW pandoc; quarto's `:::` pre-passes are routed around by the caller):
//   a Div whose Attr is ("", [w], []) with w equal to the tail's first [^ \t]+ run  -> kind "word"
//        (fallback true iff w starts with `{`: an accepted attribute block can never yield a class holding `{`);
//   any other Div                                                                  -> kind "attr"
//   no Div (the opener stayed paragraph text)                                      -> kind "refused"
//
// MINED ROWS. The `MINED` ids are the Session 262 probe ids (W/I/C/K/B/Q/S/U/R: pandoc-markdown results; c/t/m/r/s/g/x/
// d/T: div-readers; J1_: design-J1 fallback tail probes). Their SPEC TEXT is synthetic and was copied here; this
// script reads no scratch file, so it regenerates on a clean checkout. `H###` rows were added in Session 281.
// Rows containing a newline are not generated (multi-line openers are filed, plan section 8).
