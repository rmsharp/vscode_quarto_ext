function corpus() {
  const out = [];
  const seen = new Set();
  let n = 0;
  for (const [id, spec] of MINED) { if (!seen.has(spec)) { seen.add(spec); out.push([id, spec]); } }
  for (const spec of HAND) { if (!seen.has(spec)) { seen.add(spec); out.push(["H" + String(++n).padStart(3, "0"), spec]); } }
  return out;
}

// ---------------------------------------------------------------- pandoc
function expandTabs(line) {
  let out = "";
  for (const ch of line) {
    if (ch === "\t") out += " ".repeat(4 - (out.length % 4)); else out += ch;
  }
  return out;
}

function enumerateRows(dialect) {
  const rows = [];
  for (const [id, spec] of corpus()) {
    const indents = spec.includes("\t") ? [0, 1] : [0];
    for (const indent of indents) rows.push({ id, spec, dialect, indent, tailCol: indent + 3 });
  }
  return rows;
}

function buildDoc(rows) {
  let doc = "";
  rows.forEach((r, k) => {
    const opener = " ".repeat(r.indent) + ":::" + " " + r.spec;
    doc += `ZZROW${k}AZZ\n\n${opener}\n\nx\n\n:::\n\n`;
    doc += `ZZROW${k}BZZ\n\n${opener}\n}\n\nx\n\n:::\n\n`;
  });
  return doc + "ZZENDZZ\n";
}

function runPandoc(from, doc) {
  const p = spawnSync("quarto", ["pandoc", "-f", from, "-t", "json"], { input: doc, encoding: "utf8", maxBuffer: 1 << 28 });
  if (p.error || p.status !== 0) throw new Error(`quarto pandoc failed (${p.status}): ${p.error ?? p.stderr}`);
  return JSON.parse(p.stdout).blocks;
}

function pandocVersion() {
  const p = spawnSync("quarto", ["pandoc", "--version"], { encoding: "utf8" });
  if (p.error || p.status !== 0) throw new Error("quarto pandoc --version failed");
  return p.stdout.split("\n")[0].replace(/^pandoc\s+/, "").trim();
}

const sentinelOf = (b) => {
  if (b.t !== "Para" || b.c.length !== 1 || b.c[0].t !== "Str") return null;
  const m = /^ZZ(?:ROW(\d+)([AB])|END)ZZ$/.exec(b.c[0].c);
  return m ? (m[1] === undefined ? "END" : `${m[1]}${m[2]}`) : null;
};

function classify(spec, segment, where) {
  const first = segment[0];
  if (first && first.t === "Div") {
    if (segment.length !== 1) throw new Error(`${where}: Div followed by ${segment.length - 1} extra block(s)`);
    const [[id, classes, kvs]] = first.c;
    const w = /[^ \t]+/.exec(spec)?.[0];
    if (id === "" && classes.length === 1 && kvs.length === 0 && w !== undefined && classes[0] === w) {
      return { kind: "word", fallback: w.startsWith("{"), id: "", classes: [w], kvs: [] };
    }
    return { kind: "attr", fallback: false, id, classes, kvs };
  }
  if (segment.length !== 3 || segment.some((b) => b.t !== "Para")) {
    throw new Error(`${where}: refused opener produced ${segment.map((b) => b.t).join(",")}, expected 3 Para`);
  }
  return { kind: "refused", fallback: false, id: "", classes: [], kvs: [] };
}

function generateDialect([dialect, from]) {
  const rows = enumerateRows(dialect);
  const blocks = runPandoc(from, buildDoc(rows));
  const segments = new Map();
  let cur = null;
  for (const b of blocks) {
    const s = sentinelOf(b);
    if (s !== null) { cur = []; segments.set(s, cur); } else if (cur) cur.push(b); else throw new Error("block before the first sentinel");
  }
  if (!segments.has("END")) throw new Error("END sentinel missing: the document derailed");
  return rows.map((r, k) => {
    const where = `${dialect} ${r.id} indent ${r.indent}`;
    const a = segments.get(`${k}A`), b = segments.get(`${k}B`);
    if (!a || !b) throw new Error(`${where}: sentinel missing`);
    return {
      id: r.id, spec: r.spec, dialect, indent: r.indent, tailCol: r.tailCol,
      oneLine: classify(r.spec, a, where + " oneLine"),
      continuation: classify(r.spec, b, where + " continuation"),
    };
  });
}

function generate() {
  const version = pandocVersion();
  if (version !== PANDOC_VERSION) throw new Error(`pandoc ${version} is installed, the fixture is for ${PANDOC_VERSION}`);
  const rows = DIALECTS.flatMap(generateDialect);
  return {
    header: {
      pandoc: PANDOC_VERSION,
      regenerate: REGENERATE,
      note: "RAW pandoc truth for `::: <spec>` openers; synthetic specs only. spec is the text after the colon run minus the one space the generator adds, UNTRIMMED, TABs unexpanded; the opener is indent spaces + ':::' + ' ' + spec (tailCol = indent + 3). oneLine framing: opener / blank / x / blank / :::. continuation framing: opener / } / blank / x / blank / :::. kind: attr = a Div with pandoc's Attr; word = a Div whose only class is the tail's first word (fallback true iff the word starts with '{'); refused = no Div. kvs hold pandoc's DECODED values. pandoc 3.6.3 refuses every INDENTED opener (indent 1-3), so indent>0 rows are all refused.",
    },
    rows,
  };
}

function serialize(fx) {
  const esc = (s) => s.replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
  const text = `{\n"header": ${JSON.stringify(fx.header)},\n"rows": [\n${fx.rows.map((r) => JSON.stringify(r)).join(",\n")}\n]\n}\n`;
  return esc(text);
}

// ---------------------------------------------------------------- controls
// [spec, dialect, indent, expected oneLine {kind, fallback}]. Hand-checked against `quarto pandoc` 3.6.3 by Session 281.
const TAB = "\t";
const CONTROLS = [
  ["{.callout-note}", "markdown", 0, { kind: "attr", fallback: false }],
  ["{.callout-note title=\"x\"}", "markdown", 0, { kind: "attr", fallback: false }],
  ["{.callout-note data-author=O'Brien title='Note'}", "markdown", 0, { kind: "attr", fallback: false }],
  ["callout-note :::", "markdown", 0, { kind: "word", fallback: false }],
  [" {.callout-note}", "markdown", 0, { kind: "word", fallback: false }],
  ["{.callout-note!} :::", "markdown", 0, { kind: "word", fallback: true }],
  ["{callout-tip} ", "markdown", 0, { kind: "word", fallback: true }],
  ["{.a", "markdown", 0, { kind: "word", fallback: true }],
  ["{.a}x", "markdown", 0, { kind: "refused", fallback: false }],
  ["{.callout-note title}", "markdown", 0, { kind: "refused", fallback: false }],
  // B26: `\<TAB>` after `{k=a\` sits at column 9, so the TAB expands to 3 spaces (refused); after `{kkk=a\` it
  // sits at column 11 and expands to 1 space (accepted). Both at indent 0.
  ["{k=a\\" + TAB + "b}", "markdown", 0, { kind: "refused", fallback: false }],
  ["{kkk=a\\" + TAB + "b}", "markdown", 0, { kind: "attr", fallback: false }],
  ["{k=a\\" + TAB + "b}", "markdown_strict", 0, { kind: "refused", fallback: false }],
  // markdown_strict: `\ ` is no escape (space is not in the Markdown.pl set), so both spellings refuse
  ["{kkk=a\\" + TAB + "b}", "markdown_strict", 0, { kind: "refused", fallback: false }],
  // an indented `:::` is not a div opener in pandoc 3.6.3, even for an otherwise valid spec
  ["{.a}", "markdown", 0, { kind: "attr", fallback: false }],
  ["{.a}\t", "markdown", 1, { kind: "refused", fallback: false }],
];

function runControls(rows) {
  const failures = [];
  for (const [spec, dialect, indent, want] of CONTROLS) {
    const row = rows.find((r) => r.spec === spec && r.dialect === dialect && r.indent === indent);
    const label = `${JSON.stringify(spec)} (${dialect}, indent ${indent})`;
    if (!row) { failures.push(`${label}: no such row`); continue; }
    const got = row.oneLine;
    if (got.kind !== want.kind || got.fallback !== want.fallback) {
      failures.push(`${label}: expected ${want.kind}/fallback ${want.fallback}, got ${got.kind}/fallback ${got.fallback}`);
    }
  }
  return failures;
}

// ---------------------------------------------------------------- main
const mode = process.argv[2];
if (mode !== "--write" && mode !== "--check") {
  console.error("usage: truth.mjs --write | --check");
  process.exit(2);
}
const fx = generate();
const text = serialize(fx);
const count = (d) => fx.rows.filter((r) => r.dialect === d).length;
const summary = DIALECTS.map(([d]) => `${d}: ${count(d)} rows`).join(", ");
if (mode === "--write") {
  writeFileSync(FIXTURE, text);
  console.log(`wrote ${FIXTURE} (${summary})`);
  process.exit(0);
}
let bad = 0;
const control = runControls(fx.rows);
for (const f of control) { console.error("CONTROL FAILED: " + f); bad++; }
if (!existsSync(FIXTURE)) { console.error("fixture missing: " + FIXTURE); bad++; }
else {
  const committed = readFileSync(FIXTURE, "utf8");
  if (committed !== text) {
    bad++;
    const a = committed.split("\n"), b = text.split("\n");
    let shown = 0;
    for (let i = 0; i < Math.max(a.length, b.length) && shown < 10; i++) {
      if (a[i] !== b[i]) { console.error(`DIFF line ${i + 1}\n  committed:   ${a[i]}\n  regenerated: ${b[i]}`); shown++; }
    }
    console.error("fixture differs from live pandoc; regenerate with: " + REGENERATE);
  }
}
console.log(bad === 0 ? `OK (${summary}; ${CONTROLS.length} controls)` : `FAILED (${bad})`);
process.exit(bad === 0 ? 0 : 1);
